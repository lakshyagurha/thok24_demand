create table public.orders (
  id                  bigint generated by default as identity primary key,
  user_id             uuid not null references auth.users (id) on delete cascade,
  total_amount        numeric(10,2) not null,
  coupon_code         text,
  discount_amount     numeric(10,2) not null default 0,
  delivery_charge     numeric(10,2) not null default 0,
  handling_charge     numeric(10,2) not null default 0,
  final_amount        numeric(10,2) not null,
  status              text not null default 'pending', -- observed: pending, packed, way, delivered
  payment_method      text not null default 'COD',
  -- was varchar 'DD-MM-YYYY hh:mm AM'; Phase 5 parses it as Asia/Kolkata local time
  order_datetime      timestamptz not null default now(),
  delivery_date       date,
  -- NOT a time: the source stores a window like '9 AM - 2 PM', so this stays text.
  delivery_time_window text,
  -- was `location_id`; verified against the data to reference delivery_address.id,
  -- not city.id. Renamed to say so. Nullable + ON DELETE SET NULL so deleting an
  -- address does not delete order history.
  delivery_address_id bigint references public.delivery_address (id) on delete set null,
  gift                text
);
create index orders_user_id_idx on public.orders (user_id);
create index orders_delivery_address_id_idx on public.orders (delivery_address_id);
create index orders_order_datetime_idx on public.orders (order_datetime desc);

create table public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.orders (id) on delete cascade,
  -- Nullable, unlike the source: 1 source row references a product that has since been
  -- deleted. Order history must survive catalog deletions, so this is SET NULL rather
  -- than cascading the line item away.
  product_id bigint references public.products (id) on delete set null on update cascade,
  variant_id bigint references public.product_variants (id) on delete set null on update cascade,
  quantity   integer not null check (quantity > 0),
  -- ADDITION beyond a literal port -- flagged for review.
  -- The source captures no price on the line item, so a past order's composition cannot
  -- be reconstructed once catalog prices change; only the order-level total survives.
  -- Nullable so existing rows migrate untouched (NULL = unknown historical price) while
  -- new orders can record it. Drop this column if you would rather port exactly.
  unit_price numeric(10,2),
  image_url  text
);
create index order_items_order_id_idx on public.order_items (order_id);
create index order_items_product_id_idx on public.order_items (product_id);
create index order_items_variant_id_idx on public.order_items (variant_id);

-- Repeat-order recall powering BolKeOrder's "the usual" behaviour.
create table public.regular_orders (
  id              bigint generated by default as identity primary key,
  user_id         uuid not null references auth.users (id) on delete cascade,
  product_id      bigint not null references public.products (id) on delete cascade on update cascade,
  variant_id      bigint not null references public.product_variants (id) on delete cascade on update cascade,
  frequency_score integer not null default 1,
  last_ordered    timestamptz not null default now(),
  unique (user_id, product_id, variant_id)
);
create index regular_orders_user_id_idx on public.regular_orders (user_id);
create index regular_orders_product_id_idx on public.regular_orders (product_id);
create index regular_orders_variant_id_idx on public.regular_orders (variant_id);

create table public.chat_messages (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  -- 'bot' (not 'assistant') is the vocabulary both the source data and process_chat.php
  -- use; keeping it avoids rewriting 68 rows and every insert site in the bot.
  role       text not null default 'user' check (role in ('user', 'bot')),
  message    text not null,
  created_at timestamptz not null default now()
);
create index chat_messages_user_id_created_at_idx on public.chat_messages (user_id, created_at desc);

