-- DxMart: initial Postgres schema, converted from the live MariaDB `thok24` database.
--
-- Scope: consumer-only (households). There is deliberately NO role/account_type column
-- and nothing anywhere gates on user type. `wholesale_price` is carried across for
-- structural fidelity but is never referenced.
--
-- RLS is enabled here on every table but NO policies are created — policies land in the
-- next migration (Phase 2) so they can be reviewed on their own. Until then, RLS-enabled
-- tables with no policy deny all access to anon/authenticated, which is the safe default.
--
-- Conversions applied throughout:
--   int(11) AUTO_INCREMENT  -> bigint generated BY DEFAULT as identity
--                              (BY DEFAULT, not ALWAYS, so Phase 5 can preserve legacy ids)
--   decimal/double(10,2)    -> numeric(10,2)          (never float for money)
--   varchar dates           -> timestamptz / date      (see per-column notes)
--   latin1 tables           -> UTF-8 (Postgres is UTF-8 throughout)
--   int user_id             -> uuid referencing auth.users(id)

-- ---------------------------------------------------------------------------
-- Schemas
-- ---------------------------------------------------------------------------

-- Staff identity lives outside the exposed `public` schema so it is unreachable
-- via the Data API even if a policy is ever misconfigured.
create schema if not exists private;
revoke all on schema private from anon, authenticated;

