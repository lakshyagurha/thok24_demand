-- Identity itself lives in auth.users (phone/OTP). This holds the app-side profile.
-- Deliberately no role/account_type column: every user is the same consumer type.
create table public.user_profiles (
  id             uuid primary key references auth.users (id) on delete cascade,
  name           text,
  phone          text,
  status         text not null default 'active',  -- observed: 'active', 'blocked'
  -- Maps back to the old integer users.id so Phase 5 can rewire foreign keys and so
  -- the migration stays auditable. Safe to drop once cutover is verified.
  legacy_user_id bigint unique,
  created_at     timestamptz not null default now()
);

-- Keeps user_profiles in step with auth.users on signup. Must be SECURITY DEFINER to
-- write a row the new user cannot yet write themselves; kept in `private` (not `public`)
-- so it is not exposed as a callable Data API endpoint, with search_path pinned.
create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.user_profiles (id, phone, name)
  values (
    new.id,
    new.phone,
    nullif(new.raw_user_meta_data ->> 'name', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

